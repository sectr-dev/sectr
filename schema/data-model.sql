-- ============================================================================
-- Sectr canonical DDL — the whole data model: the `Journal` store (events)
-- plus the `Registry` store (all other tables). One file in MVP (both traits
-- are implemented over the same DB); the Journal/Registry split is at the
-- trait level.
--
-- Source of truth for the database layout. sectr-common's migration runner
-- consumes this file. Canonical dialect is Postgres; `sectr dev` runs SQLite.
--
-- SQLite dialect mapping (the subset used here is chosen so the translation
-- is mechanical — sectr-common ships the SQLite variant derived from this):
--   uuid            -> TEXT      (canonical lowercase; values generated client-side)
--   timestamptz     -> TEXT      (ISO-8601 RFC 3339, always UTC 'Z')
--   jsonb           -> TEXT      (JSON as text; payload validated at the app layer
--                                 against schema/event.schema.json)
--   gen_random_uuid() -> omitted  (SQLite: client-generated; ids are UUIDv7)
--   now()           -> omitted    (SQLite: client-supplied created_at)
-- Partial unique indexes (leases) are supported by SQLite >= 3.8.
--
-- Notes:
-- - `events.id` is UUIDv7, generated by the journal writer, time-ordered.
-- - `events.seq` is per-session, monotonic, gap-free within a turn, starts
--   at 0, and is assigned ONLY by the journal writer (sectr-worker);
--   gap-free within an invocation. UNIQUE(session_id, seq) makes concurrent
--   append races fail loudly.
-- - The `events.type` CHECK list MUST stay in sync with the `eventType` enum
--   in schema/event.schema.json (enforced by schema/conformance.py).
-- ============================================================================

BEGIN;

-- ----------------------------------------------------------------------------
-- Tenancy & identity
-- ----------------------------------------------------------------------------

CREATE TABLE orgs (
    id          uuid PRIMARY KEY,
    name        text NOT NULL,
    slug        text NOT NULL UNIQUE,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id          uuid PRIMARY KEY,
    org_id      uuid NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    email       text NOT NULL,
    name        text,
    clerk_user_id text,  -- Clerk `sub`, the account's identity key (no linking by email); NULL only on pre-Clerk rows
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (org_id, email)
);

CREATE UNIQUE INDEX idx_users_clerk ON users(clerk_user_id) WHERE clerk_user_id IS NOT NULL;

-- ----------------------------------------------------------------------------
-- Alpha allowlist — UNUSED since Clerk signup
-- ----------------------------------------------------------------------------

-- Admin-curated emails for the old POST /alpha/provision flow. Clerk signup
-- removed that endpoint, the `allowlist-add` subcommand and every
-- reader/writer; Clerk sign-in is the only signup path. The table is kept
-- (migration 0005 stays applied; a DROP is irreversible and buys nothing)
-- and may be dropped by a later migration.
CREATE TABLE alpha_allowlist (
    email          text PRIMARY KEY,
    added_at       timestamptz NOT NULL DEFAULT now(),
    added_by       text NOT NULL,
    provisioned_at timestamptz
);

-- ----------------------------------------------------------------------------
-- Apps, keys, deployments, secrets (registry)
-- ----------------------------------------------------------------------------

CREATE TABLE apps (
    id          uuid PRIMARY KEY,
    org_id      uuid NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    name        text NOT NULL,
    slug        text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (org_id, slug)
);

-- kind = 'platform'  : control-plane key (CLI + dashboard), org-scoped
-- kind = 'invocation': the app's TRUSTED-BACKEND key (minting credential;
--                      full data plane for its app) — never shipped to
--                      browsers in multi-user apps
-- kind = 'user'      : browser token (sks_) minted per page load by the
--                      app's backend (POST /tokens); bound to one
--                      external_user_id, short TTL, expired == revoked
-- Only key_hash is stored; keys are never readable back.
CREATE TABLE api_keys (
    id               uuid PRIMARY KEY,
    org_id           uuid NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
    app_id           uuid REFERENCES apps(id) ON DELETE CASCADE,  -- NULL for platform keys
    kind             text NOT NULL CHECK (kind IN ('platform', 'invocation', 'user')),
    name             text NOT NULL,
    key_hash         text NOT NULL UNIQUE,
    external_user_id text,  -- user tokens only: the bound end-user identity
    expires_at       timestamptz,  -- user tokens only: hard expiry
    minted_by_key_id uuid REFERENCES api_keys(id) ON DELETE CASCADE,  -- user tokens only: the minting invocation key (its revocation revokes this token)
    created_at       timestamptz NOT NULL DEFAULT now(),
    last_used_at     timestamptz,
    revoked_at       timestamptz,
    CHECK ((kind = 'platform' AND app_id IS NULL) OR (kind = 'invocation' AND app_id IS NOT NULL) OR (kind = 'user' AND app_id IS NOT NULL AND external_user_id IS NOT NULL AND expires_at IS NOT NULL AND minted_by_key_id IS NOT NULL))
);

-- Serves the periodic purge of expired user tokens.
CREATE INDEX idx_api_keys_user_expiry ON api_keys(expires_at) WHERE kind = 'user';

-- Browser login for `sectr auth login` (device flow). One row per
-- login REQUEST. `expires_at` is the request's 10-minute approve-and-collect
-- window; the key minted on consume is an ordinary api_keys row with no
-- expiry, and GC of old requests never touches it (key_id is SET NULL).
CREATE TABLE cli_logins (
    id               uuid PRIMARY KEY,
    device_code_hash text NOT NULL UNIQUE,   -- sha256 of the 32-byte device code; plaintext only ever in the CLI
    user_code        text NOT NULL UNIQUE,   -- 8 chars, BCDFGHJKLMNPQRSTVWXZ alphabet, shown as XXXX-XXXX
    client_name      text NOT NULL,          -- the CLI's hostname, <= 64 chars, display only
    status           text NOT NULL DEFAULT 'pending'
                     CHECK (status IN ('pending', 'approved', 'denied', 'consumed')),
    org_id           uuid REFERENCES orgs(id) ON DELETE CASCADE,        -- set on approve
    approved_by      uuid REFERENCES api_keys(id) ON DELETE SET NULL,   -- the approving platform key
    key_id           uuid REFERENCES api_keys(id) ON DELETE SET NULL,   -- the minted key, set on consume
    created_at       timestamptz NOT NULL DEFAULT now(),
    expires_at       timestamptz NOT NULL
);
CREATE INDEX idx_cli_logins_expiry ON cli_logins(expires_at);

CREATE TABLE deployments (
    id            uuid PRIMARY KEY,
    app_id        uuid NOT NULL REFERENCES apps(id) ON DELETE CASCADE,
    version       bigint NOT NULL,
    status        text NOT NULL DEFAULT 'building'
                  CHECK (status IN ('building', 'active', 'failed', 'retired')),
    manifest      jsonb NOT NULL,       -- authoritative manifest from SECTR_MANIFEST import
    artifact_uri  text,                 -- tarball location (set once built)
    build_ref     text,                 -- opaque builder-specific in-flight-build id (e.g. a build op id); set while `building`, NULL otherwise
    error         text,                 -- failure reason of a `failed` build (truncated build-output tail, or the stale-sweep message); NULL otherwise
    endpoint_url  text,                 -- endpoint deployments: the customer's serve-mode sidecar, woken over HTTP per turn; NULL = managed (built and run by the server's platform)
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (app_id, version)
);

-- Write-only by contract: no read API ever exposes values.
CREATE TABLE secrets (
    id               uuid PRIMARY KEY,
    app_id           uuid NOT NULL REFERENCES apps(id) ON DELETE CASCADE,
    key              text NOT NULL,
    value_encrypted  text NOT NULL,
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    UNIQUE (app_id, key)
);

-- ----------------------------------------------------------------------------
-- Sessions & journal
-- ----------------------------------------------------------------------------

-- status transitions: active -> awaiting_approval <-> active -> ended
-- origin: which principal class created the session ('api' = an end-user
-- agent via an invocation key or browser token, 'playground' = dashboard
-- via a platform principal).
-- external_user_id: the session's owner when created via a browser token
-- — (app_id, external_user_id) scopes browser-token access;
-- NULL = backend/platform-created (never visible to user tokens).
CREATE TABLE sessions (
    id               uuid PRIMARY KEY,
    app_id           uuid NOT NULL REFERENCES apps(id),
    deployment_id    uuid NOT NULL REFERENCES deployments(id),  -- sessions pin to the deployment they started on
    route            text NOT NULL,
    origin           text NOT NULL DEFAULT 'playground' CHECK (origin IN ('api', 'playground')),
    external_user_id text,
    status           text NOT NULL DEFAULT 'active'
                     CHECK (status IN ('active', 'awaiting_approval', 'ended')),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz,
    ended_at         timestamptz
);

CREATE INDEX idx_sessions_app ON sessions(app_id, created_at DESC);

CREATE TABLE events (
    id             uuid PRIMARY KEY,      -- UUIDv7, journal-writer-generated
    session_id     uuid NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    deployment_id  uuid NOT NULL,
    seq            bigint NOT NULL CHECK (seq >= 0),
    type           text NOT NULL CHECK (type IN (
                       -- runner-emitted (validated + journaled by the sidecar)
                       'MESSAGE_START',
                       'MESSAGE_DELTA',
                       'MESSAGE_END',
                       'TOOL_CALL',
                       'TOOL_APPROVAL_REQUIRED',
                       'ERROR',
                       'NO_MORE_ACTIONS',
                       'TRANSCRIPT_COMPACTED',
                       -- platform-emitted
                       'SESSION_CREATED',
                       'INVOCATION_STARTED',
                       'TOOL_RESULT',
                       'TOOL_APPROVAL_GRANTED',
                       'TOOL_APPROVAL_DENIED',
                       'SESSION_ERROR'
                   )),
    payload        jsonb NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
    extra          jsonb NOT NULL,       -- unknown envelope fields, preserved verbatim (forward compat)
    created_at     timestamptz NOT NULL,
    UNIQUE (session_id, seq)
);
-- A deployment's recent turn starts and session errors (the wakes summary).
CREATE INDEX idx_events_turn_starts ON events (deployment_id, created_at DESC)
    WHERE type IN ('INVOCATION_STARTED', 'SESSION_ERROR');

-- jsonb can't hold U+0000 in a string, so PgJournal stores every string and
-- object key in `payload` and `extra` with NUL escaped as U+FDD0 '0' and
-- U+FDD0 itself as U+FDD0 U+FDD0 (a Unicode noncharacter, so other text is
-- stored as it is), and unescapes on read. Read rows through the journal,
-- not raw SQL, to see the original text. SQLite stores NUL directly.

-- Client SSE catch-up is `WHERE session_id = $1 AND seq > $last ORDER BY seq`;
-- served by the UNIQUE index above (Postgres LISTEN/NOTIFY wakes the tail;
-- SQLite dev journal polls).

-- ----------------------------------------------------------------------------
-- Leases (runner lifecycle)
-- ----------------------------------------------------------------------------

-- At most one live lease per session; released_at IS NULL marks it live.
-- Claim/heartbeat policy lives in sectr-worker; this table only records it.
CREATE TABLE leases (
    id            uuid PRIMARY KEY,
    session_id    uuid NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    runner_id     text NOT NULL,
    invocation_id uuid,
    claimed_at    timestamptz NOT NULL DEFAULT now(),
    heartbeat_at  timestamptz NOT NULL DEFAULT now(),
    expires_at    timestamptz NOT NULL,
    released_at   timestamptz
);

CREATE UNIQUE INDEX idx_leases_session_live ON leases(session_id) WHERE released_at IS NULL;
CREATE INDEX idx_leases_expiry ON leases(expires_at) WHERE released_at IS NULL;

COMMIT;
