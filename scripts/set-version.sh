#!/usr/bin/env bash
# set-version.sh — Sectr's version choreography.
#
# Sectr is versioned in lockstep: ONE version for sectr-cli, sectr-server,
# sectr-worker, sdk-python (the `sectr` PyPI package), dashboard, docs-site,
# and @sectr/copilotkit (js/copilotkit). The source of truth is
# [workspace.package] `version` in the root Cargo.toml; the SDK, dashboard,
# docs and npm manifests must match it.
# The npm `sectr` shell (js/sectr) is deliberately outside the lockstep: it
# stays at 0.0.0 until it carries SDK code.
#
# Usage:
#   scripts/set-version.sh 0.0.2       # set the version everywhere
#   scripts/set-version.sh --bump patch  # compute current+1 component, set, print new version
#   scripts/set-version.sh --next patch  # print current+1 component, change nothing
#   scripts/set-version.sh --check     # verify all manifests agree (CI)
#
# Releases are cut by `just release` (RELEASING.md), which bumps on a
# release branch, verifies, tags and publishes.
set -euo pipefail
cd "$(dirname "$0")/.."

CARGO_TOML=Cargo.toml
CARGO_LOCK=Cargo.lock
PYPROJECT=sdk-python/pyproject.toml
PACKAGE_JSON=dashboard/package.json
DOCS_PACKAGE_JSON=docs-site/package.json
DASH_LOCK=dashboard/package-lock.json
DOCS_LOCK=docs-site/package-lock.json
NPM_PACKAGE_JSON=js/copilotkit/package.json
NPM_LOCK=js/copilotkit/package-lock.json

fail() { echo "error: $*" >&2; exit 1; }

# Read each manifest's version without depending on toolchain-specific tools.
read_cargo()   { python3 - "$CARGO_TOML" <<'EOF'
import sys, re
text = open(sys.argv[1]).read()
m = re.search(r'^\[workspace\.package\]\n(?:^[^\[].*\n)*?^version = "([^"]+)"', text, re.M)
print(m.group(1) if m else "")
EOF
}

# Compute the next lockstep version from the current one.
# 0.0.1 -patch-> 0.0.2 | 0.0.1 -minor-> 0.1.0 | 0.0.1 -major-> 1.0.0
next_version() {
    local cur bump
    cur=$(read_cargo)
    bump=$1
    cur=${cur%%-*}  # ignore any prerelease suffix for bump arithmetic
    IFS=. read -r MA MI PA <<<"$cur"
    case "$bump" in
        patch) echo "$MA.$MI.$((PA + 1))" ;;
        minor) echo "$MA.$((MI + 1)).0" ;;
        major) echo "$((MA + 1)).0.0" ;;
        *) fail "unknown bump component '$bump' (want patch|minor|major)" ;;
    esac
}
read_python()  { python3 -c 'import sys,re; t=open(sys.argv[1]).read(); m=re.search(r"^\[project\]\n(?:^[^\[].*\n)*?^version = \"([^\"]+)\"", t, re.M); print(m.group(1) if m else "")' "$PYPROJECT"; }
read_package() { python3 -c 'import sys,json; print(json.load(open(sys.argv[1]))["version"])' "$1"; }

# Read a package-lock.json's embedded version: the header and the packages.""
# entry must AGREE (they encode the same root package); disagreement = "".
read_lock() { python3 - "$1" <<'EOF'
import sys, json
lock = json.load(open(sys.argv[1]))
versions = {lock.get("version"), lock.get("packages", {}).get("", {}).get("version")}
versions.discard(None)
print(next(iter(versions)) if len(versions) == 1 else "")
EOF
}

# Rewrite the version in all three lockstep manifests.
set_version() {
    local VER=$1

    python3 - "$CARGO_TOML" "$VER" <<'EOF'
import sys, re
path, ver = sys.argv[1], sys.argv[2]
text = open(path).read()
new, n = re.subn(r'(\[workspace\.package\]\n(?:^[^\[].*\n)*?^version = ")([^"]+)(")', r'\g<1>' + ver + r'\g<3>', text, count=1, flags=re.M)
assert n == 1, "workspace.package version not found"
open(path, "w").write(new)
EOF

    python3 - "$PYPROJECT" "$VER" <<'EOF'
import sys, re
path, ver = sys.argv[1], sys.argv[2]
text = open(path).read()
new, n = re.subn(r'(\[project\]\n(?:^[^\[].*\n)*?^version = ")([^"]+)(")', r'\g<1>' + ver + r'\g<3>', text, count=1, flags=re.M)
assert n == 1, "project version not found"
open(path, "w").write(new)
EOF

# Rewrite the version in one package.json (dashboard + docs-site are
# 4-space indented, npm packages npm's own 2-space).
set_package_json_version() {
    python3 - "$1" "$VER" "${2:-4}" <<'EOF'
import sys, json, collections
path, ver, indent = sys.argv[1], sys.argv[2], int(sys.argv[3])
data = json.load(open(path), object_pairs_hook=collections.OrderedDict)
assert "version" in data, "version key not found"
data["version"] = ver
with open(path, "w") as f:
    json.dump(data, f, indent=indent, ensure_ascii=False)
    f.write("\n")
EOF
}

    set_package_json_version "$PACKAGE_JSON"
    set_package_json_version "$DOCS_PACKAGE_JSON"
    set_package_json_version "$NPM_PACKAGE_JSON" 2

    # Lockfiles carry the version in TWO places (header + packages."") and
    # aren't regenerated by a manifest edit — rewrite both textually so the
    # rest of npm's own formatting stays byte-identical (a JSON round-trip
    # would churn every line). Exactly 2 matches: the name-anchored lines are
    # unique to the root package; anything else fails fast. (Found drifting
    # 2026-09-22: dashboard lock said 0.1.0 while the workspace was 0.0.4.)
    set_lock_version() {
        python3 - "$1" "$2" "$VER" <<'EOF'
import sys, re
path, name, ver = sys.argv[1], sys.argv[2], sys.argv[3]
text = open(path).read()
# Header ("name"\n"version") and packages."" ("" entry: "name"\n"version").
pat = r'("name": "' + re.escape(name) + r'",\n\s*"version": ")(?:[^"]+)(")'
new, n = re.subn(pat, r'\g<1>' + ver + r'\g<2>', text)
assert n == 2, f"expected 2 lock version entries, found {n}"
open(path, "w").write(new)
EOF
    }

    set_lock_version "$DASH_LOCK" dashboard
    set_lock_version "$DOCS_LOCK" docs-site
    set_lock_version "$NPM_LOCK" @sectr/copilotkit

    python3 - "$CARGO_LOCK" "$VER" <<'EOF'
import sys, re
path, ver = sys.argv[1], sys.argv[2]
text = open(path).read()
# Workspace member versions live in the lock too; rewrite them for the five
# sectr-* crates (never deps of external crates, so the name-anchored match
# is unambiguous). Cargo's own `cargo update` would need a toolchain here.
new, n = re.subn(r'(^name = "sectr-(?:cli|common|conformance|server|worker)"\nversion = ")([^"]+)(")', r'\g<1>' + ver + r'\g<3>', text, flags=re.M)
assert n == 5, f"expected 5 sectr-* lock entries, found {n}"
open(path, "w").write(new)
EOF

    echo "set version $VER in $CARGO_TOML, $CARGO_LOCK, $PYPROJECT, $PACKAGE_JSON, $DOCS_PACKAGE_JSON, $DASH_LOCK, $DOCS_LOCK, $NPM_PACKAGE_JSON, $NPM_LOCK"
    echo "next: commit (releases go through \`just release\`)"
}

if [[ "${1:-}" == "--next" ]]; then
    [[ -n "${2:-}" ]] || fail "--next needs a component: patch|minor|major"
    next_version "$2"
    exit 0
fi

if [[ "${1:-}" == "--bump" ]]; then
    shift
    [[ -n "${1:-}" ]] || fail "--bump needs a component: patch|minor|major"
    NEW=$(next_version "$1")
    set_version "$NEW" >&2
    echo "$NEW"
    exit 0
fi

if [[ "${1:-}" == "--check" ]]; then
    C=$(read_cargo); P=$(read_python); N=$(read_package "$PACKAGE_JSON"); D=$(read_package "$DOCS_PACKAGE_JSON"); J=$(read_package "$NPM_PACKAGE_JSON")
    status=0
    L=$(python3 - "$CARGO_LOCK" <<'EOF'
import sys, re
seen = set()
for m in re.finditer(r'^name = "(sectr-(?:cli|common|conformance|server|worker))"\nversion = "([^"]+)"', open(sys.argv[1]).read(), re.M):
    seen.add(m.group(2))
print(seen.pop() if len(seen) == 1 else "")
EOF
)
    DL=$(read_lock "$DASH_LOCK")
    TDL=$(read_lock "$DOCS_LOCK")
    JL=$(read_lock "$NPM_LOCK")
    for entry in "$CARGO_TOML:$C" "$CARGO_LOCK:$L" "$PYPROJECT:$P" "$PACKAGE_JSON:$N" "$DOCS_PACKAGE_JSON:$D" "$DASH_LOCK:$DL" "$DOCS_LOCK:$TDL" "$NPM_PACKAGE_JSON:$J" "$NPM_LOCK:$JL"; do
        name=${entry%%:*}; ver=${entry#*:}
        echo "$name: ${ver:-<missing>}"
        if [[ -z "$ver" ]]; then status=1
        elif [[ "$ver" != "$C" ]]; then echo "  -> MISMATCH (expected $C)"; status=1; fi
    done
    [[ $status -eq 0 ]] && echo "all manifests agree at $C"
    exit $status
fi

VER=${1:-}
[[ "$VER" =~ ^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$ ]] || { echo "usage: $0 <semver> | --bump patch|minor|major | --check"; exit 1; }

set_version "$VER"