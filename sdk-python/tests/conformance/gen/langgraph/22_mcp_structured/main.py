import asyncio
import os

from langchain.agents import create_agent
from langchain_mcp_adapters.client import MultiServerMCPClient

from sectr import AgentApp
from sectr.adapters.langgraph import as_langgraph_tool, langgraph

from endpoint import model
from tools import lookup_order

mcp = MultiServerMCPClient(
    {"conformance": {"transport": "streamable_http", "url": os.environ["SECTR_CONFORMANCE_URL"] + "/mcp"}}
)
mcp_tools = asyncio.run(mcp.get_tools())

graph = create_agent(
    model(),
    tools=[as_langgraph_tool(lookup_order), *mcp_tools],
    system_prompt="You are a customer-support agent for a small shop.",
    name="mcp_structured",
)

app = AgentApp(name="conf-langgraph-mcp_structured")
app.add_route("/chat", langgraph(graph))
