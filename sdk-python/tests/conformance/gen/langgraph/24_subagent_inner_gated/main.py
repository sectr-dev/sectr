from langchain.agents import create_agent

from sectr import AgentApp
from sectr.adapters.langgraph import as_langgraph_tool, langgraph
from sectr.tools import tool

from endpoint import model
from tools import track_parcel, refund

specialist = create_agent(
    model(),
    tools=[as_langgraph_tool(track_parcel), as_langgraph_tool(refund)],
    system_prompt="You are a shipping specialist. Answer from your tools, in one sentence.",
    name="specialist",
)


@tool
async def ask_specialist(input: str) -> str:
    """Ask the shipping specialist about an order."""
    result = await specialist.ainvoke({"messages": [{"role": "user", "content": input}]})
    return result["messages"][-1].text


graph = create_agent(
    model(),
    tools=[as_langgraph_tool(ask_specialist)],
    system_prompt="You are a customer-support agent for a small shop.",
    name="subagent_inner_gated",
)

app = AgentApp(name="conf-langgraph-subagent_inner_gated")
app.add_route("/chat", langgraph(graph))
