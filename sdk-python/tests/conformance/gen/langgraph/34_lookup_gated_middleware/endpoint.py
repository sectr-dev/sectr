import os

from langchain_anthropic import ChatAnthropic
from langchain_openai import ChatOpenAI
from langchain_openrouter import ChatOpenRouter


def model():
    url = os.environ["SECTR_CONFORMANCE_URL"]
    endpoint = os.environ["SECTR_CONFORMANCE_ENDPOINT"]
    if endpoint == "openai_chat":
        return ChatOpenAI(
            model="mock", base_url=url + "/v1", api_key="conformance", max_retries=0
        )
    if endpoint == "openrouter":
        return ChatOpenRouter(
            model="anthropic/claude-haiku-5.5",
            base_url=url + "/v1",
            api_key="conformance",
            max_retries=0,
        )
    if endpoint == "openai_responses":
        return ChatOpenAI(
            model="gpt-5.4-nano",
            base_url=url + "/v1",
            api_key="conformance",
            max_retries=0,
            use_responses_api=True,
        )
    if endpoint == "anthropic":
        return ChatAnthropic(
            model="claude-haiku-5-5",
            base_url=url,
            api_key="conformance",
            max_retries=0,
            thinking={"type": "adaptive", "display": "summarized"},
        )
    raise ValueError(f"unknown conformance endpoint {endpoint!r}")
