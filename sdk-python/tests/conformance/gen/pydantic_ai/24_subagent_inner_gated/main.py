from pydantic_ai import Agent, RunContext, Tool

from sectr import AgentApp
from sectr.adapters.pydantic_ai import pydantic_ai

from endpoint import model
from tools import track_parcel, refund

specialist = Agent(
    model(),
    name="specialist",
    instructions="You are a shipping specialist. Answer from your tools, in one sentence.",
    tools=[track_parcel, Tool(refund, requires_approval=True)],
)


async def ask_specialist(ctx: RunContext, input: str) -> str:
    """Ask the shipping specialist about an order."""
    result = await specialist.run(input, usage=ctx.usage)
    return result.output


agent = Agent(
    model(),
    name="subagent_inner_gated",
    instructions="You are a customer-support agent for a small shop.",
    tools=[ask_specialist],
)

app = AgentApp(name="conf-pydantic-ai-subagent_inner_gated")
app.add_route("/chat", pydantic_ai(agent))
