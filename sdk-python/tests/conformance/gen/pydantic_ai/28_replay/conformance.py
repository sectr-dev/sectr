"""The conformance harness's tool backend: each tool stub POSTs its arguments
to `$SECTR_CONFORMANCE_URL/tools/<name>`, and the running case decides the
outcome: return a value, raise, or exit the process (a crash mid-tool).

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

import os
from typing import Any

import httpx


async def run_tool(name: str, **arguments: Any) -> Any:
    async with httpx.AsyncClient(timeout=None) as client:
        response = await client.post(
            f"{os.environ['SECTR_CONFORMANCE_URL']}/tools/{name}", json=arguments
        )
    response.raise_for_status()
    outcome = response.json()
    if "raise" in outcome:
        raise RuntimeError(outcome["raise"])
    if "exit" in outcome:
        os._exit(outcome["exit"])
    return outcome["return"]
