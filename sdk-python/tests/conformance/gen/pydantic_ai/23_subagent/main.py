specialist = Agent(
    model(),
    name="specialist",
    instructions="You are a shipping specialist. Answer from your tools, in one sentence.",
    tools=[track_parcel],
)


async def ask_specialist(ctx: RunContext, input: str) -> str:
    """Ask the shipping specialist about an order."""
    result = await specialist.run(input, usage=ctx.usage)
    return result.output


async def escalate(ctx: RunContext, input: str) -> str:
    """Escalate an order question to the shipping specialist (needs approval)."""
    result = await specialist.run(input, usage=ctx.usage)
    return result.output


async def ask_manager(ctx: RunContext, input: str) -> str:
    """Ask the shipping manager about an order."""
    result = await specialist.run(input, usage=ctx.usage)
    return result.output


