from agents import Agent

from sectr import AgentApp
from sectr.adapters.openai_agents import openai_agents

from endpoint import model, model_settings
from tools import track_parcel

specialist = Agent(
    name="specialist",
    instructions="You are a shipping specialist. Answer from your tools, in one sentence.",
    model=model(),
    model_settings=model_settings(),
    tools=[track_parcel],
)

agent = Agent(
    name="subagent",
    instructions="You are a customer-support agent for a small shop.",
    model=model(),
    model_settings=model_settings(),
    tools=[specialist.as_tool(tool_name="ask_specialist", tool_description="Ask the shipping specialist about an order."), specialist.as_tool(tool_name="escalate", tool_description="Escalate an order question to the shipping specialist (needs approval).", needs_approval=True), specialist.as_tool(tool_name="ask_manager", tool_description="Ask the shipping manager about an order.")],
)

app = AgentApp(name="conf-openai-agents-subagent")
app.add_route("/chat", openai_agents(agent))
