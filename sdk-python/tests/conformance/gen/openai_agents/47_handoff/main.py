from agents import Agent

from sectr import AgentApp
from sectr.adapters.openai_agents import openai_agents

from endpoint import model, model_settings
from tools import lookup_order

orders = Agent(
    name="orders",
    instructions="You are the order desk. Answer from your tools, in one sentence.",
    model=model(),
    model_settings=model_settings(),
    tools=[lookup_order],
)

agent = Agent(
    name="handoff",
    instructions="You are a shop's front desk. Hand order questions to the order desk.",
    model=model(),
    model_settings=model_settings(),
    handoffs=[orders],
)

orders.handoffs = [agent]

app = AgentApp(name="conf-openai-agents-handoff")
app.add_route("/chat", openai_agents(agent))
