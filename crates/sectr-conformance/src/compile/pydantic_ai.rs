//! The pydantic-ai backend: an `Agent` on `endpoint.py`'s model. Tools are
//! plain functions, as in the pydantic-ai example; gated ones are
//! registered as `Tool(f, requires_approval=True)` (native deferred tools).
//! The harness's MCP server is an `MCPToolset`; its gated tools are wrapped
//! with `.approval_required(...)`. A subagent is another `Agent`, run by a
//! delegating tool.

use super::{
  MCP_URL, gated_mcp, has_mcp, models, output, py_str, std_imports, subagents, tool_names,
  tool_stubs,
};
use crate::scenario::Scenario;

pub fn main_py(scenario: &Scenario) -> String {
  let id = scenario.id;
  let instructions = py_str(scenario.agent.instructions);
  let tools_import = match tool_names(scenario) {
    n if n.is_empty() => String::new(),
    n => format!("from tools import {n}\n"),
  };
  let outer: Vec<(&str, bool)> = scenario
    .agent
    .tools
    .iter()
    .map(|t| (t.name, t.gated))
    .chain(scenario.agent.subagents.iter().map(|t| (t.name, t.gated)))
    .collect();
  let tools_arg = if outer.is_empty() {
    String::new()
  } else {
    format!("    tools=[{}],\n", registered(&outer))
  };
  let subagents = subagents(scenario);
  let gated = outer.iter().any(|(_, gated)| *gated)
    || subagents.iter().any(|a| a.tools.iter().any(|t| t.gated));
  let mut agent_import = vec!["Agent"];
  if !subagents.is_empty() {
    agent_import.push("RunContext");
  }
  if gated {
    agent_import.push("Tool");
  }
  let agent_import = agent_import.join(", ");
  // Agent delegation: a tool awaiting the subagent's run, sharing the
  // caller's usage.
  let subagents: String = subagents
    .iter()
    .map(|a| {
      let tools: Vec<(&str, bool)> = a.tools.iter().map(|t| (t.name, t.gated)).collect();
      format!(
        "\n{name} = Agent(\n    model(),\n    name={name_str},\n    instructions={instructions},\n    \
         tools=[{tools}],\n)\n",
        name = a.name,
        name_str = py_str(a.name),
        instructions = py_str(a.instructions),
        tools = registered(&tools),
      )
    })
    .chain(scenario.agent.subagents.iter().map(|t| {
      format!(
        "\n\nasync def {name}(ctx: RunContext, input: str) -> str:\n    \"\"\"{description}\"\"\"\n    \
         result = await {agent}.run(input, usage=ctx.usage)\n    return result.output\n",
        name = t.name,
        description = t.description,
        agent = t.agent.name,
      )
    }))
    // Two blank lines after a function.
    .chain((!scenario.agent.subagents.is_empty()).then(|| "\n".to_string()))
    .collect();
  let output = output(scenario, "output_type");
  let (output_import, output_class, output_arg) = (output.import, output.class, output.arg);
  let (os_import, mcp_import, mcp_arg) = if has_mcp(scenario) {
    (
      "import os\n\n",
      "from pydantic_ai.mcp import MCPToolset\n",
      match gated_mcp(scenario) {
        None => format!("    toolsets=[MCPToolset({MCP_URL})],\n"),
        Some(names) => format!(
          "    toolsets=[\n        MCPToolset({MCP_URL}).approval_required(\n            \
           lambda ctx, tool_def, args: tool_def.name in {{{names}}}\n        )\n    ],\n"
        ),
      },
    )
  } else {
    ("", "", String::new())
  };
  format!(
    r#""""Conformance case `{id}` on pydantic-ai.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{os_import}{output_import}from pydantic_ai import {agent_import}
{mcp_import}
from sectr import AgentApp
from sectr.adapters.pydantic_ai import pydantic_ai

from endpoint import model
{tools_import}{output_class}{subagents}
agent = Agent(
    model(),
    name="{id}",
    instructions={instructions},
{tools_arg}{mcp_arg}{output_arg})

app = AgentApp(name="conf-pydantic-ai-{id}")
app.add_route("/chat", pydantic_ai(agent))
"#
  )
}

pub fn tools_py(scenario: &Scenario) -> String {
  let models = models(scenario);
  format!(
    r#""""Tools for conformance case `{id}` on pydantic-ai: plain async stubs whose
outcome the running case decides.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{typing}{pydantic}from conformance import run_tool
{models}{stubs}"#,
    id = scenario.id,
    // Its own block: there's no other third-party import.
    pydantic = if models.import.is_empty() {
      String::new()
    } else {
      format!("{}\n", models.import)
    },
    models = models.classes,
    typing = std_imports(scenario),
    stubs = tool_stubs(scenario, |_| None),
  )
}

/// Tools as registered: gated ones as `Tool(f, requires_approval=True)`.
fn registered(tools: &[(&str, bool)]) -> String {
  let registered: Vec<String> = tools
    .iter()
    .map(|(name, gated)| {
      if *gated {
        format!("Tool({name}, requires_approval=True)")
      } else {
        (*name).to_string()
      }
    })
    .collect();
  registered.join(", ")
}
