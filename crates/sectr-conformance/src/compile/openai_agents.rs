//! The openai-agents backend: an `Agent` on `endpoint.py`'s model. Tools are
//! `@function_tool`s; gated ones use the SDK's native `needs_approval=True`.
//! The harness's MCP server is an `MCPServerStreamableHttp` in
//! `mcp_servers`; its gated tools are named in `require_approval=`. A
//! subagent is an `Agent` exposed with `as_tool()`. A handoff agent is an
//! `Agent` in `handoffs=[...]`; one that hands back gets the agent under
//! test in its own `handoffs` once that's built.

use super::{
  MCP_URL, gated_mcp, has_mcp, models, names, output, py_str, std_imports, subagents, tool_names,
  tool_stubs,
};
use crate::scenario::Scenario;

pub fn main_py(scenario: &Scenario) -> String {
  let id = scenario.id;
  let instructions = py_str(scenario.agent.instructions);
  let tools_import = match tool_names(scenario) {
    n if n.is_empty() => String::new(),
    n => format!("from tools import {n}\n"),
  };
  let mut tools: Vec<String> = scenario.agent.tools.iter().map(|t| t.name.into()).collect();
  tools.extend(scenario.agent.subagents.iter().map(|t| {
    let gated = if t.gated { ", needs_approval=True" } else { "" };
    format!(
      "{}.as_tool(tool_name={}, tool_description={}{gated})",
      t.agent.name,
      py_str(t.name),
      py_str(t.description)
    )
  }));
  let tools_arg = if tools.is_empty() {
    String::new()
  } else {
    format!("    tools=[{}],\n", tools.join(", "))
  };
  let subagents: String = subagents(scenario)
    .iter()
    .map(|a| {
      format!(
        "\n{name} = Agent(\n    name={name_str},\n    instructions={instructions},\n    \
         model=model(),\n    model_settings=model_settings(),\n    tools=[{tools}],\n)\n",
        name = a.name,
        name_str = py_str(a.name),
        instructions = py_str(a.instructions),
        tools = names(a.tools),
      )
    })
    .collect();
  let handoff_agents: String = scenario
    .agent
    .handoffs
    .iter()
    .map(|a| {
      format!(
        "\n{name} = Agent(\n    name={name_str},\n    instructions={instructions},\n    \
         model=model(),\n    model_settings=model_settings(),\n    tools=[{tools}],\n)\n",
        name = a.name,
        name_str = py_str(a.name),
        instructions = py_str(a.instructions),
        tools = names(a.tools),
      )
    })
    .collect();
  let handoffs_arg = if scenario.agent.handoffs.is_empty() {
    String::new()
  } else {
    let names: Vec<&str> = scenario.agent.handoffs.iter().map(|a| a.name).collect();
    format!("    handoffs=[{}],\n", names.join(", "))
  };
  let backs: String = scenario
    .agent
    .handoffs
    .iter()
    .filter(|a| a.back)
    .map(|a| format!("{}.handoffs = [agent]\n", a.name))
    .collect();
  let backs = if backs.is_empty() {
    backs
  } else {
    format!("\n{backs}")
  };
  let output = output(scenario, "output_type");
  let (output_import, output_class, output_arg) = (output.import, output.class, output.arg);
  let (os_import, mcp_import, mcp_server, mcp_arg) = if has_mcp(scenario) {
    (
      "import os\n\n",
      "from agents.mcp import MCPServerStreamableHttp\n",
      {
        let approval = gated_mcp(scenario)
          .map(|names| {
            let always: Vec<String> = names
              .split(", ")
              .map(|n| format!("{n}: \"always\""))
              .collect();
            format!("    require_approval={{{}}},\n", always.join(", "))
          })
          .unwrap_or_default();
        let structured = if scenario.agent.mcp.structured {
          "    use_structured_content=True,\n"
        } else {
          ""
        };
        format!(
          "\nmcp_server = MCPServerStreamableHttp(\n    params={{\"url\": {MCP_URL}}},\n    \
           name=\"conformance\",\n{approval}{structured})\n"
        )
      },
      "    mcp_servers=[mcp_server],\n",
    )
  } else {
    ("", "", String::new(), "")
  };
  format!(
    r#""""Conformance case `{id}` on openai-agents.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{os_import}from agents import Agent
{mcp_import}{output_import}
from sectr import AgentApp
from sectr.adapters.openai_agents import openai_agents

from endpoint import model, model_settings
{tools_import}{output_class}{mcp_server}{subagents}{handoff_agents}
agent = Agent(
    name="{id}",
    instructions={instructions},
    model=model(),
    model_settings=model_settings(),
{tools_arg}{handoffs_arg}{mcp_arg}{output_arg})
{backs}
app = AgentApp(name="conf-openai-agents-{id}")
app.add_route("/chat", openai_agents(agent))
"#
  )
}

pub fn tools_py(scenario: &Scenario) -> String {
  let models = models(scenario);
  format!(
    r#""""Tools for conformance case `{id}` on openai-agents: `@function_tool` stubs
whose outcome the running case decides.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{typing}from agents import function_tool
{pydantic}
from conformance import run_tool
{models}{stubs}"#,
    id = scenario.id,
    pydantic = models.import,
    models = models.classes,
    typing = std_imports(scenario),
    stubs = tool_stubs(scenario, |t| {
      Some(if t.gated {
        "@function_tool(needs_approval=True)"
      } else {
        "@function_tool"
      })
    }),
  )
}
