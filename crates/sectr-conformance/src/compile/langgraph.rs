//! The langgraph backend: `langchain.agents.create_agent` over
//! `endpoint.py`'s chat model. Tools are sectr `@tool`s converted
//! with `as_langgraph_tool`, as in the langgraph example; gated ones are
//! `@tool(needs_approval=True)`. The harness's MCP server's tools come from
//! `langchain-mcp-adapters`' `MultiServerMCPClient`, listed at import.
//! Gated MCP tools use langchain's own approval, `HumanInTheLoopMiddleware`,
//! which the adapter honors with Sectr's pause. A subagent is a named
//! `create_agent` graph, run by a Sectr `@tool` (langchain's subagent shape).
//! A scenario gated another way ([`Gate`]) has plain LangChain `@tool`s
//! instead, gated by `HumanInTheLoopMiddleware` or by `as_langgraph_tool(t,
//! needs_approval=True)`.

use super::{
  MCP_URL, has_mcp, models, output, py_str, std_imports, subagents, tool_names, tool_stubs,
};
use crate::agent::ToolSpec;
use crate::scenario::{Gate, Scenario};

pub fn main_py(scenario: &Scenario) -> String {
  let id = scenario.id;
  let instructions = py_str(scenario.agent.instructions);
  let tools_import = match tool_names(scenario) {
    n if n.is_empty() => String::new(),
    n => format!("from tools import {n}\n"),
  };
  let outer: Vec<String> = scenario
    .agent
    .tools
    .iter()
    .map(|t| tool_arg(scenario.gate, t))
    .chain(
      scenario
        .agent
        .subagents
        .iter()
        .map(|t| format!("as_langgraph_tool({})", t.name)),
    )
    .collect();
  let tools = outer.join(", ");
  let subagents = subagents(scenario);
  let adapter_import = if tools.contains("as_langgraph_tool(") || !subagents.is_empty() {
    "as_langgraph_tool, langgraph"
  } else {
    "langgraph"
  };
  let tool_import = if subagents.is_empty() {
    ""
  } else {
    "from sectr.tools import tool\n"
  };
  // A subagent is its own `create_agent` graph, run by a Sectr tool.
  let subagents: String = subagents
    .iter()
    .map(|a| {
      let tools: Vec<&str> = a.tools.iter().map(|t| t.name).collect();
      format!(
        "\n{name} = create_agent(\n    model(),\n    tools=[{tools}],\n    \
         system_prompt={instructions},\n    name={name_str},\n)\n",
        name = a.name,
        name_str = py_str(a.name),
        instructions = py_str(a.instructions),
        tools = converted(&tools),
      )
    })
    .chain(scenario.agent.subagents.iter().map(|t| {
      let decorator = if t.gated {
        "@tool(needs_approval=True)"
      } else {
        "@tool"
      };
      format!(
        "\n\n{decorator}\nasync def {name}(input: str) -> str:\n    \"\"\"{description}\"\"\"\n    \
         result = await {agent}.ainvoke({{\"messages\": [{{\"role\": \"user\", \"content\": input}}]}})\n    \
         return result[\"messages\"][-1].text\n",
        name = t.name,
        description = t.description,
        agent = t.agent.name,
      )
    }))
    // Two blank lines after a function.
    .chain((!scenario.agent.subagents.is_empty()).then(|| "\n".to_string()))
    .collect();
  let output = output(scenario, "response_format");
  let (output_import, output_class, output_arg) = (output.import, output.class, output.arg);
  let (stdlib_import, mcp_import, mcp_tools) = if has_mcp(scenario) {
    (
      "import asyncio\nimport os\n\n",
      "from langchain_mcp_adapters.client import MultiServerMCPClient\n",
      format!(
        "\nmcp = MultiServerMCPClient(\n    {{\"conformance\": {{\"transport\": \"streamable_http\", \"url\": {MCP_URL}}}}}\n)\n\
         mcp_tools = asyncio.run(mcp.get_tools())\n"
      ),
    )
  } else {
    ("", "", String::new())
  };
  // The tools `HumanInTheLoopMiddleware` gates: gated MCP tools, and under
  // `Gate::Middleware` the agent's own gated tools.
  let own: &[ToolSpec] = match scenario.gate {
    Gate::Middleware => scenario.agent.tools,
    Gate::Native | Gate::Wrapped => &[],
  };
  let interrupt_on: Vec<String> = own
    .iter()
    .chain(scenario.agent.mcp.tools)
    .filter(|t| t.gated)
    .map(|t| format!("{}: True", py_str(t.name)))
    .collect();
  let (middleware_import, middleware_arg) = if interrupt_on.is_empty() {
    ("", String::new())
  } else {
    (
      "from langchain.agents.middleware import HumanInTheLoopMiddleware\n",
      format!(
        "    middleware=[HumanInTheLoopMiddleware(interrupt_on={{{}}})],\n",
        interrupt_on.join(", ")
      ),
    )
  };
  let tools = if mcp_tools.is_empty() {
    tools
  } else if tools.is_empty() {
    "*mcp_tools".to_string()
  } else {
    format!("{tools}, *mcp_tools")
  };
  format!(
    r#""""Conformance case `{id}` on langgraph.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{stdlib_import}from langchain.agents import create_agent
{middleware_import}{mcp_import}{output_import}
from sectr import AgentApp
from sectr.adapters.langgraph import {adapter_import}
{tool_import}
from endpoint import model
{tools_import}{output_class}{mcp_tools}{subagents}
graph = create_agent(
    model(),
    tools=[{tools}],
    system_prompt={instructions},
    name="{id}",
{middleware_arg}{output_arg})

app = AgentApp(name="conf-langgraph-{id}")
app.add_route("/chat", langgraph(graph))
"#
  )
}

pub fn tools_py(scenario: &Scenario) -> String {
  let models = models(scenario);
  let (what, langchain, sectr, decorator): (_, _, _, fn(&ToolSpec) -> Option<&'static str>) =
    match scenario.gate {
      Gate::Native => (
        "sectr `@tool` stubs (main.py\nconverts them with `as_langgraph_tool`)",
        "",
        "from sectr.tools import tool\n",
        |t| {
          Some(if t.gated {
            "@tool(needs_approval=True)"
          } else {
            "@tool"
          })
        },
      ),
      Gate::Middleware | Gate::Wrapped => (
        "plain LangChain `@tool`\nstubs (main.py gates the gated ones)",
        "from langchain_core.tools import tool\n",
        "",
        |_| Some("@tool"),
      ),
    };
  format!(
    r#""""Tools for conformance case `{id}` on langgraph: {what} whose outcome the running case
decides.

Generated by sectr-conformance. Do not edit: run `sectr-conformance gen`.
"""

{typing}{langchain}{pydantic}{sectr}
from conformance import run_tool
{models}{stubs}"#,
    id = scenario.id,
    pydantic = models.import,
    models = models.classes,
    typing = std_imports(scenario),
    stubs = tool_stubs(scenario, decorator),
  )
}

/// The agent's own tool `t` in `create_agent(tools=[...])`, gated `gate`'s
/// way.
fn tool_arg(gate: Gate, t: &ToolSpec) -> String {
  match gate {
    Gate::Native => format!("as_langgraph_tool({})", t.name),
    Gate::Wrapped if t.gated => format!("as_langgraph_tool({}, needs_approval=True)", t.name),
    Gate::Middleware | Gate::Wrapped => t.name.to_string(),
  }
}

/// Sectr tools converted for a `ToolNode`, comma-separated.
fn converted(names: &[&str]) -> String {
  let converted: Vec<String> = names
    .iter()
    .map(|n| format!("as_langgraph_tool({n})"))
    .collect();
  converted.join(", ")
}
